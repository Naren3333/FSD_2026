"""Actual gateway, PostgreSQL, object storage, Kafka and authorization integration.

Creates uniquely named test data; never drops databases or deletes user data.
Requires the local Compose stack, .env and httpx. Assertions are never mocked.
"""
import json
import subprocess
import time
from pathlib import Path
from uuid import UUID, uuid4

import httpx
from jsonschema import Draft202012Validator, FormatChecker

ROOT = Path(__file__).resolve().parents[1]
ENV = dict(line.split("=", 1) for line in (ROOT / ".env").read_text().splitlines() if line and not line.startswith("#"))
BASE = "http://localhost:8000/api"
CONTRACTS = {"chatbot": "question-chatbot-agent"}  # gateway path → contract file


def docker(*args: str, input: str | None = None, check: bool = True) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["docker", "compose", *args], cwd=ROOT, input=input, text=True, capture_output=True, check=check, timeout=90)


def login(username: str, password_key: str) -> httpx.Client:
    res = httpx.post("http://localhost:8081/realms/learning/protocol/openid-connect/token", data={"client_id": "learning-e2e", "grant_type": "password", "username": username, "password": ENV[password_key]}, timeout=15)
    assert res.status_code == 200, f"Local identity login failed: {res.status_code}"
    return httpx.Client(base_url=BASE, headers={"Authorization": "Bearer " + res.json()["access_token"]}, timeout=25)


def service_token(client_id: str) -> str:
    secret = ENV[client_id.upper().replace("-", "_") + "_CLIENT_SECRET"]
    res = httpx.post("http://localhost:8081/realms/learning/protocol/openid-connect/token", data={"client_id": client_id, "client_secret": secret, "grant_type": "client_credentials"}, timeout=15)
    assert res.status_code == 200, f"Service account login failed for {client_id}: {res.status_code}"
    return res.json()["access_token"]


def ai_core_status(token: str) -> int:
    """POST a valid embed request to the private ai-core from inside its own container (it has no published port)."""
    script = ("import json,sys,urllib.request,urllib.error\n"
              "req=urllib.request.Request('http://localhost:8080/v1/inference',data=json.dumps({'operation':'embed','input':'fractions','model_profile':'default','billed_to':{'user_id':'integration-test','org_id':'local-school','role':'teacher'}}).encode(),headers={'Authorization':'Bearer '+sys.stdin.read().strip(),'Content-Type':'application/json'})\n"
              "try:\n print(urllib.request.urlopen(req,timeout=10).status)\n"
              "except urllib.error.HTTPError as e:\n print(e.code)\n")
    return int(docker("exec", "-T", "ai-core", "python", "-c", script, input=token).stdout.strip())


def request(client: httpx.Client, method: str, path: str, status: int = 200, **kwargs: object):
    response = client.request(method, path, **kwargs)
    assert response.status_code == status, f"{method} {path}: expected {status}, got {response.status_code}: {response.text[:400]}"
    data = response.json() if response.content else None
    if data is not None:
        import re
        service, _, resource = path.lstrip("/").partition("/")
        contract = json.loads((ROOT / f"contracts/http/{CONTRACTS.get(service, service)}.openapi.json").read_text())
        route = "/v1/" + resource.split("?")[0]
        for template, methods in contract["paths"].items():
            if re.fullmatch(re.sub(r"\{[^}]+\}", "[^/]+", template), route) and method.lower() in methods:
                schema = methods[method.lower()]["responses"].get(str(status), {}).get("content", {}).get("application/json", {}).get("schema")
                if schema:
                    resolved = {**schema, "components": contract.get("components", {})}
                    Draft202012Validator(resolved, format_checker=FormatChecker()).validate(data)
                break
    return data


def content_sql(sql: str) -> str:
    return docker("exec", "-T", "postgres", "psql", "-U", "content", "-d", "content", "-At", "-c", sql).stdout.strip()


def eventually(action, predicate, label: str):
    deadline = time.monotonic() + 60
    while time.monotonic() < deadline:
        value = action()
        if predicate(value):
            return value
        time.sleep(1)
    raise AssertionError(f"Timed out: {label}")


def replay(service: str, topic: str, resource: str, fresh_id: bool = False) -> str:
    # resource is a UUID generated by this test or returned by a verified API.
    resource = str(UUID(resource))
    row = docker("exec", "-T", "postgres", "psql", "-U", service, "-d", service, "-At", "-c", f"SELECT body FROM outbox WHERE partition_key='{resource}' AND topic='{topic}'").stdout.strip()
    event = json.loads(row)
    schema = json.loads((ROOT / f"contracts/events/{topic}.schema.json").read_text())
    Draft202012Validator(schema, format_checker=FormatChecker()).validate(event)
    if fresh_id:
        event["event_id"] = str(uuid4())
    docker("exec", "-T", "kafka", "/opt/kafka/bin/kafka-console-producer.sh", "--bootstrap-server", "kafka:9092", "--topic", topic, input=json.dumps(event)+"\n")
    return event["event_id"]


def main() -> None:
    teacher = login("teacher", "TEACHER_PASSWORD")
    student = login("student", "STUDENT_PASSWORD")
    other = login("other-teacher", "OTHER_TEACHER_PASSWORD")
    teacher_profile = request(teacher, "POST", "/identity/me", json={})
    student_profile = request(student, "POST", "/identity/me", json={})
    request(other, "POST", "/identity/me", json={})
    assert httpx.get(BASE+"/identity/classrooms").status_code == 401
    room = request(teacher, "POST", "/identity/classrooms", 201, json={"name": "Integration " + str(uuid4())[:8]})
    request(student, "POST", "/identity/classrooms", 403, json={"name": "Forbidden"})
    request(other, "GET", f"/identity/classrooms/{room['id']}/access", 403)
    # Teachers enroll by the username the student signs in with; only the classroom's teacher sees its roster.
    assert student_profile["username"] == "student" and student_profile["display_name"] == "Student Local", student_profile
    request(teacher, "POST", f"/identity/classrooms/{room['id']}/enrollments", 422, json={"username": "nobody-" + str(uuid4())[:8]})
    request(other, "POST", f"/identity/classrooms/{room['id']}/enrollments", 403, json={"username": "student"})
    enrolled = request(teacher, "POST", f"/identity/classrooms/{room['id']}/enrollments", json={"username": "STUDENT"})
    assert enrolled["student_id"] == student_profile["id"]
    roster_path = f"/identity/classrooms/{room['id']}/students"
    assert request(teacher, "GET", roster_path) == [{"id": student_profile["id"], "username": "student", "display_name": "Student Local"}]
    request(student, "GET", roster_path, 403)
    request(other, "GET", roster_path, 403)
    skill = request(teacher, "POST", "/curriculum/nodes", 201, json={"kind": "skill", "name": "Integration exact decimals", "parent_id": None})
    doc = request(teacher, "POST", f"/content/documents?classroom_id={room['id']}&title=Integration", 201, content=b"A fraction is a part of a whole.", headers={"Content-Type": "text/plain"})
    assert doc["status"] == "extracted" and doc["chunks"][0]["text"] == "A fraction is a part of a whole."
    request(other, "GET", f"/content/documents/{doc['id']}", 403)
    request(student, "GET", f"/content/documents/{doc['id']}")
    original = student.get(f"/content/documents/{doc['id']}/original")
    assert original.status_code == 200 and original.content == b"A fraction is a part of a whole."
    pdf = request(teacher, "POST", f"/content/documents?classroom_id={room['id']}&title=PDF", 201, content=b"%PDF-1.7\n", headers={"Content-Type": "application/pdf"})
    assert pdf["status"] == "indexing" and pdf["doc_type"] == "teaching_material"
    # The indexing worker sends the PDF to ai-core: without provider keys the job waits to be retried; with them,
    # this header-only file fails as CORRUPT. Neither invents chunks.
    def indexing_state() -> str:
        job = content_sql(f"SELECT attempts||' '||coalesce(last_error,'') FROM index_jobs WHERE document_id='{UUID(pdf['id'])}'")
        return job or request(teacher, "GET", f"/content/documents/{pdf['id']}")["status"]
    state = eventually(indexing_state, lambda v: "AI_PROVIDER_NOT_CONFIGURED" in v or v == "failed", "PDF indexing attempt")
    if state == "failed":
        assert request(teacher, "GET", f"/content/documents/{pdf['id']}")["failure_reason"] == "CORRUPT"
    else:
        request(teacher, "POST", f"/content/documents/{pdf['id']}/reindex", 409)
    assert content_sql(f"SELECT count(*) FROM document_chunks WHERE document_id='{UUID(pdf['id'])}'") == "0"
    request(student, "POST", f"/content/documents/{pdf['id']}/reindex", 403)
    request(teacher, "POST", f"/content/documents/{doc['id']}/reindex", 409)
    request(teacher, "GET", f"/content/documents/{pdf['id']}/figures/0123456789abcdef.png", 404)
    # Rubrics and marking schemes are for teachers only.
    rubric = request(teacher, "POST", f"/content/documents?classroom_id={room['id']}&title=Rubric&doc_type=rubric", 201, content=b"Band 4: explains clearly.", headers={"Content-Type": "text/plain"})
    request(teacher, "POST", f"/content/documents?classroom_id={room['id']}&title=Bad&doc_type=answers", 422, content=b"x", headers={"Content-Type": "text/plain"})
    assert rubric["id"] in [d["id"] for d in request(teacher, "GET", f"/content/documents?classroom_id={room['id']}")]
    assert rubric["id"] not in [d["id"] for d in request(student, "GET", f"/content/documents?classroom_id={room['id']}")]
    request(student, "GET", f"/content/documents/{rubric['id']}", 404)
    assert student.get(f"/content/documents/{rubric['id']}/original").status_code == 404
    # PDFs may be up to 50 MiB through the gateway; text stays at 5 MiB, refused by Content itself.
    request(teacher, "POST", f"/content/documents?classroom_id={room['id']}&title=Big", 413, content=b"a" * (7 << 20), headers={"Content-Type": "text/plain"})
    # Search: the caller's own classroom access, then ai-core for the query vector (503 without provider keys).
    query = {"classroom_id": room["id"], "query": "What is a fraction?"}
    request(other, "POST", "/content/search", 403, json=query)
    request(student, "POST", "/content/search", 422, json={**query, "query": " "})
    searched = student.post("/content/search", json=query)
    assert searched.status_code in (200, 503), searched.text
    if searched.status_code == 503:
        assert searched.json()["error"]["code"] == "SEARCH_UNAVAILABLE"
    else:
        request(student, "POST", "/content/search", json=query)
    # Chat: a thread needs classroom access; each turn searches with the user's own token and streams an answer
    # from ai-core (an AI_UNAVAILABLE error event without provider keys, never a made-up answer).
    assert httpx.post(BASE + "/chatbot/threads", json={"classroom_id": room["id"]}).status_code == 401
    request(other, "POST", "/chatbot/threads", 403, json={"classroom_id": room["id"]})
    chat = request(student, "POST", "/chatbot/threads", 201, json={"classroom_id": room["id"]})
    with student.stream("POST", f"/chatbot/threads/{chat['id']}/messages", json={"content": "What is a fraction?"}, timeout=60) as streamed:
        assert streamed.status_code == 200 and streamed.headers["content-type"].startswith("text/event-stream")
        events = [block.split("\n")[0].removeprefix("event: ") for block in streamed.read().decode().strip().split("\n\n")]
    assert events[-1] in ("done", "error"), events
    turn = request(student, "GET", f"/chatbot/threads/{chat['id']}/messages")["messages"]
    assert [m["role"] for m in turn] == ["user", "assistant"] and turn[0]["content"] == "What is a fraction?"
    assert turn[1]["outcome"] in ("answered", "no_results", "error")
    request(other, "GET", f"/chatbot/threads/{chat['id']}/messages", 404)
    request(teacher, "GET", f"/chatbot/threads/{chat['id']}/messages", 404)
    assert [t["id"] for t in request(student, "GET", f"/chatbot/threads?classroom_id={room['id']}")["threads"]] == [chat["id"]]
    # Each user's AI spend today against their daily allowance (ADR 0003): $5 for a student, $10 for a teacher.
    assert request(student, "GET", "/chatbot/usage")["limit_usd"] == 5.0
    assert request(teacher, "GET", "/chatbot/usage")["limit_usd"] == 10.0
    assert httpx.get(BASE + "/chatbot/usage").status_code == 401
    assessment = request(teacher, "POST", "/assessment/assessments", 201, json={"classroom_id": room["id"], "title": "Decimal test", "questions": [{"prompt": "0.1 + 0.2?", "type": "numerical", "answer": "0.3", "tolerance": "0", "options": [], "skill_id": skill["id"]}, {"prompt": "Which is a fraction?", "type": "multiple_choice", "answer": "1/2", "tolerance": "", "options": ["1/2", "word"], "skill_id": skill["id"]}]})
    public = request(student, "GET", f"/assessment/assessments/{assessment['id']}")
    assert all("answer" not in q and "tolerance" not in q for q in public["questions"])
    submission = request(student, "POST", f"/assessment/assessments/{assessment['id']}/submissions", 201, json={"answers": {assessment["questions"][0]["id"]: "0.30", assessment["questions"][1]["id"]: "word"}})
    request(student, "POST", f"/assessment/assessments/{assessment['id']}/submissions", 409, json={"answers": {assessment["questions"][0]["id"]: "0.30", assessment["questions"][1]["id"]: "word"}})
    grades = eventually(lambda: request(teacher, "GET", f"/grading/evaluations?classroom_id={room['id']}"), lambda rows: len(rows) == 1, "draft grading")
    grade = grades[0]
    assert grade["status"] == "draft" and sum(e["awarded"] for e in grade["evidence"]) == 1
    # A student sees only their own finalized results: the draft stays with the teacher.
    mine_path = f"/grading/evaluations/mine?classroom_id={room['id']}"
    assert request(student, "GET", mine_path) == []
    request(teacher, "GET", mine_path, 403)
    request(other, "GET", mine_path, 403)
    performance_path = f"/analytics/performance/{student_profile['id']}?classroom_id={room['id']}"
    assert request(teacher, "GET", performance_path)["skills"] == []
    request(student, "POST", f"/grading/evaluations/{grade['id']}/finalize", 403, json={"reason": "Forbidden", "overrides": {}})
    request(other, "POST", f"/grading/evaluations/{grade['id']}/finalize", 403, json={"reason": "Forbidden", "overrides": {}})
    request(teacher, "POST", f"/grading/evaluations/{grade['id']}/finalize", json={"reason": "Integration teacher review", "overrides": {}})
    request(teacher, "POST", f"/grading/evaluations/{grade['id']}/finalize", 409, json={"reason": "Duplicate", "overrides": {}})
    mine = request(student, "GET", mine_path)
    assert [r["id"] for r in mine] == [grade["id"]] and mine[0]["status"] == "finalized" and mine[0]["finalized_at"]
    assert [(e["question_id"], e["correct"]) for e in mine[0]["evidence"]] == [(q["id"], c) for q, c in zip(assessment["questions"], [True, False])]
    result = eventually(lambda: request(teacher, "GET", performance_path), lambda result: len(result["skills"]) == 1, "analytics consumption")
    assert result["skills"][0]["attempted"] == 2 and result["skills"][0]["correct"] == 1 and result["skills"][0]["observed_accuracy"] == 0.5
    assert result["skills"][0]["evidence_status"] == "insufficient_evidence"
    request(student, "GET", f"/analytics/performance/{teacher_profile['id']}?classroom_id={room['id']}", 403)
    request(other, "GET", performance_path, 403)
    docker("restart", "grading", "analytics")
    replay("assessment", "assessment.submitted.v1", submission["id"])
    replay("grading", "grading.finalized.v1", grade["id"])
    duplicate_id = replay("grading", "grading.finalized.v1", grade["id"], fresh_id=True)
    eventually(lambda: docker("exec", "-T", "postgres", "psql", "-U", "analytics", "-d", "analytics", "-At", "-c", f"SELECT count(*) FROM inbox WHERE event_id='{duplicate_id}'").stdout.strip(), lambda value: value == "1", "duplicate processing")
    assert request(teacher, "GET", performance_path)["skills"] == result["skills"]
    assert len(request(teacher, "GET", f"/grading/evaluations?classroom_id={room['id']}")) == 1
    # Removing a student keeps their grades but ends their access to the classroom.
    remove_path = f"/identity/classrooms/{room['id']}/enrollments/{student_profile['id']}"
    request(other, "DELETE", remove_path, 403)
    request(student, "DELETE", remove_path, 403)
    request(teacher, "DELETE", remove_path)
    request(teacher, "DELETE", remove_path, 404)
    assert request(teacher, "GET", roster_path) == []
    request(student, "GET", mine_path, 403)
    assert room["id"] not in [r["id"] for r in request(student, "GET", "/identity/classrooms")]
    assert len(request(teacher, "GET", f"/grading/evaluations?classroom_id={room['id']}")) == 1
    for role, database in [("identity", "grading"), ("chatbot", "content"), ("aicore", "chatbot"), ("chatbot", "aicore")]:
        isolation = docker("exec", "-T", "postgres", "psql", "-U", role, "-d", database, "-c", "SELECT 1", check=False)
        assert isolation.returncode != 0 and "permission denied" in isolation.stderr.lower(), (role, database)
    migrations = docker("exec", "-T", "postgres", "psql", "-U", "content", "-d", "content", "-At", "-c", "SELECT string_agg(version::text, ',' ORDER BY version) FROM schema_migrations").stdout.strip()
    assert migrations == "1,2", migrations
    migrations = docker("exec", "-T", "postgres", "psql", "-U", "identity", "-d", "identity", "-At", "-c", "SELECT string_agg(version::text, ',' ORDER BY version) FROM schema_migrations").stdout.strip()
    assert migrations == "1,2", migrations
    vector = docker("exec", "-T", "postgres", "psql", "-U", "content", "-d", "content", "-At", "-c", "SELECT count(*) FROM pg_extension WHERE extname='vector'").stdout.strip()
    assert vector == "1", "pgvector is not installed in Content's database"
    # Service accounts reach the private AI service (200 with provider keys, 503 without); people do not.
    for client_id in ["content-indexer", "question-chatbot-agent"]:
        assert ai_core_status(service_token(client_id)) in (200, 503)
    assert ai_core_status(student.headers["Authorization"].removeprefix("Bearer ")) == 403
    print("PASS: gateway auth, classroom isolation, enrollment by username, rosters, unenrollment, curriculum, S3 upload/extraction, PDF indexing jobs, teacher-only rubrics, search access, chat threads and streaming, AI spend allowance, answer-key secrecy, submissions, draft grading, teacher finalization, students' own finalized results, Kafka analytics, consumer restart, duplicate event and business-key idempotency, student privacy, database isolation, numbered migrations, pgvector, AI service accounts.")


if __name__ == "__main__":
    main()
